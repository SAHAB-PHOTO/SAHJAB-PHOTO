export function getZone(wilaya: string): Zone {
  return wilayaZone[wilaya] ?? 1;
}

/**
 * حساب تكلفة التوصيل تلقائياً حسب الشركة + الولاية + نوع التوصيل + قيمة الطلب.
 * التوصيل المجاني للمنزل عند تجاوز 5000 دج متاح في ولايات الشمال (المنطقتان 1 و2).
 */
export function computeShipping(
  courier: Courier,
  wilaya: string,
  type: "home" | "desk",
  subtotal: number,
): number {
  const zone = getZone(wilaya);
  const base = type === "home" ? courier.homeFee : courier.deskFee;
  if (type === "home" && subtotal >= 5000 && zone <= 2) return 0;
  return base + zoneSurcharge[zone];
}
